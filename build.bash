#!/usr/bin/env bash
# build.bash: builds compiled.luau from the source. Two steps:
#   1. organizes the assets: the images of assets/remake and assets/legacy are written, as base64 text, into
#      src/ui/themes/icons/raw.luau. An icon built into the code needs no request to the repo (see ui/services/assetsService)
#   2. darklua bundles main.luau and its modules into compiled.luau, with darklua.json
#
# usage: ./build.bash
# darklua is looked for in DARKLUA (if set), then the PATH, then this folder, then ~/.cargo/bin
#
# Not built into the code: the files in SKIPPED_NAMES, and any image bigger than MAX_BYTES. Those are asked for from the
# repo when they are needed.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

ASSETS_DIR="$ROOT/assets"
RAW_FILE="$ROOT/src/ui/themes/icons/raw.luau"
OUTPUT="$ROOT/compiled.luau"
FOLDERS=("remake" "legacy")

# the images that are not built into the code, by file name. The logo is not used yet
SKIPPED_NAMES=("infinite-yield-logo.png" "logo.png")
# an image bigger than this (bytes) is not built into the code
MAX_BYTES=65536

find_darklua() {
	if [ -n "${DARKLUA:-}" ]; then
		echo "$DARKLUA"
	elif command -v darklua >/dev/null 2>&1; then
		command -v darklua
	elif [ -x "$ROOT/darklua" ]; then
		echo "$ROOT/darklua"
	elif [ -x "$HOME/.cargo/bin/darklua" ]; then
		echo "$HOME/.cargo/bin/darklua"
	else
		return 1
	fi
}

DARKLUA_BIN="$(find_darklua)" || {
	echo "darklua was not found. Install it (cargo install darklua) or set DARKLUA=/path/to/darklua" >&2
	exit 1
}

is_skipped() {
	local name="$1"
	local skipped
	for skipped in "${SKIPPED_NAMES[@]}"; do
		if [ "$name" = "$skipped" ]; then
			return 0
		fi
	done
	return 1
}

# writes the lua table of one folder of assets/ (the images inside it, as base64 text)
write_folder() {
	local folder="$1"
	local file name size

	echo "	[\"$folder\"] = {"

	for file in "$ASSETS_DIR/$folder"/*.png; do
		[ -e "$file" ] || continue

		name="$(basename "$file")"

		if is_skipped "$name"; then
			echo "skipped $folder/$name (not built into the code)" >&2
			continue
		fi

		size="$(wc -c < "$file")"
		if [ "$size" -gt "$MAX_BYTES" ]; then
			echo "skipped $folder/$name ($size bytes, more than $MAX_BYTES)" >&2
			continue
		fi

		# base64 can wrap its lines, so they are joined: the text is one line in the table
		printf '\t\t["%s"] = "%s",\n' "${name%.png}" "$(base64 < "$file" | tr -d '\n')"
	done

	echo "	},"
}

echo "organizing the assets"
{
	echo "-- generated by build.bash from assets/remake and assets/legacy. Run build.bash again instead of editing it"
	echo "-- the images are base64 text (see utils/base64), read back into the files they were"
	echo "return {"

	for folder in "${FOLDERS[@]}"; do
		write_folder "$folder"
	done

	echo "}"
} > "$RAW_FILE"

echo "bundling with $("$DARKLUA_BIN" --version)"
"$DARKLUA_BIN" process main.luau "$OUTPUT" -c darklua.json

echo "built $OUTPUT ($(wc -c < "$OUTPUT") bytes)"
